#!/bin/bash
#
# Build a small static library that overrides libm's double-precision
# exp/log/pow/sin/cos/tan/asin/acos/atan/atan2 with the correctly rounded
# implementations from CORE-MATH (https://core-math.gitlabpages.inria.fr/).
#
# The verification reference outputs were generated with glibc 2.27, whose
# libm (IBM Accurate Mathematical Library) is correctly rounded for exactly
# these functions; glibc >= 2.28 is not (1 ulp errors for a small fraction
# of arguments). Correct rounding is unique, so linking this library restores
# the glibc-2.27 results on a recent system. Other functions (tanh, log10,
# ...) were not correctly rounded in glibc 2.27 and are left to the system
# libm on purpose.
#
# usage: build_coremath.sh <outdir>
#   -> <outdir>/libcoremath_rn.a ; link it before -lm, e.g. with the
#      linux_amd64_flang optfile:  export CR_LIBM=<outdir>/libcoremath_rn.a
# env: CC (default cc), CFLAGS (default -O2), CORE_MATH_COMMIT,
#      CR_FUNCS (default list below)

set -e
out=$1
if [ -z "$out" ] ; then echo "usage: $0 <outdir>" ; exit 1 ; fi
CC=${CC:-cc}
CFLAGS="${CFLAGS:--O2} -fno-fast-math -w"
CORE_MATH_COMMIT=${CORE_MATH_COMMIT:-018fa97cbdacf59924b899a9dfa422d532cb2bb7}
CR_FUNCS=${CR_FUNCS:-"exp log pow sin cos tan asin acos atan atan2"}
url=https://gitlab.inria.fr/core-math/core-math/-/raw/$CORE_MATH_COMMIT/src/binary64

mkdir -p $out/src $out/obj
wrap=$out/obj/wrap.c
echo '/* generated by build_coremath.sh */' > $wrap
objs=$out/obj/wrap.o
for f in $CR_FUNCS ; do
  mkdir -p $out/src/$f
  case $f in
    log)   extra="dint.h" ;;
    pow)   extra="pow.h dint.h qint.h" ;;
    atan2) extra="tint.h" ;;
    *)     extra="" ;;
  esac
  for s in $f.c $extra ; do
    test -s $out/src/$f/$s || curl -sSfL --retry 3 -o $out/src/$f/$s $url/$f/$s
  done
  $CC $CFLAGS -I$out/src/$f -c $out/src/$f/$f.c -o $out/obj/$f.o
  objs="$objs $out/obj/$f.o"
  case $f in
    pow|atan2) echo "double cr_$f(double,double); double $f(double x,double y){return cr_$f(x,y);}" >> $wrap ;;
    *)         echo "double cr_$f(double); double $f(double x){return cr_$f(x);}" >> $wrap ;;
  esac
done
$CC $CFLAGS -c $wrap -o $out/obj/wrap.o
rm -f $out/libcoremath_rn.a
ar rcs $out/libcoremath_rn.a $objs
echo "built $out/libcoremath_rn.a (CORE-MATH $CORE_MATH_COMMIT: $CR_FUNCS)"
